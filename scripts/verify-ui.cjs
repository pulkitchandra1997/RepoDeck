    await page.getByRole('button', { name: 'Settings', exact: true }).click();
    if (!(await page.getByRole('button', { name: 'Close settings' }).evaluate(el => el === document.activeElement))) throw new Error('Settings did not receive focus');
    await page.keyboard.press('Shift+Tab');
    if (!(await page.getByRole('button', { name: 'Save settings' }).evaluate(el => el === document.activeElement))) throw new Error('Settings focus escaped');
    await page.keyboard.press('Escape');
    if (await page.getByRole('dialog').count()) throw new Error('Escape did not close settings');
    await page.getByRole('button', { name: 'Settings', exact: true }).click();
