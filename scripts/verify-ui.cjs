    await page.keyboard.press('Escape');
    await page.keyboard.press('Tab');
    if (!(await modal.evaluate(el => el === document.activeElement))) throw new Error('Pending save focus escaped');
    await page.screenshot({ path: `.tools/screenshots/settings-saving-${width}.png`, fullPage: true });
    await page.evaluate(() => window.__rejectSettingsSave());
    await modal.getByRole('alert').filter({ hasText: 'Fixture disk unavailable' }).waitFor();
