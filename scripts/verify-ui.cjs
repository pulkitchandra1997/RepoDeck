    await longRow.click();
    const branch = longRow.locator('.repo-name small > span');
    if (await branch.getAttribute('title') !== await branch.textContent()) throw new Error('Truncated branch does not expose its full value');
    if (!(await page.locator('.repo-row').evaluateAll(rows => rows.every(row => {
      const name = row.querySelector('.repo-name').getBoundingClientRect();
      const status = row.lastElementChild.getBoundingClientRect();
      return name.bottom <= status.top && row.scrollWidth <= row.clientWidth;
    })))) throw new Error(`Repository name and status overlap or overflow at ${width}`);
    if (!(await longRow.evaluate(el => el.scrollWidth <= el.clientWidth))) throw new Error(`Long repository row overflows at ${width}`);
