    await page.getByRole('button', { name: /storefront.*feature/ }).click();
    await page.getByRole('tab', { name: 'Repositories', exact: true }).focus();
    await page.keyboard.press('ArrowRight');
    await page.getByRole('tabpanel', { name: 'Files', exact: true }).waitFor();
    await page.keyboard.press('Home');
    await page.getByRole('tabpanel', { name: 'Repositories', exact: true }).waitFor();
    await page.getByRole('button', { name: /src\/checkout.ts/ }).click();
    await page.getByText('+const timeout = 3000;', { exact: false }).waitFor();
    const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth);
    if (overflow) throw new Error(`Horizontal document overflow at ${width}`);
    await page.screenshot({ path: `.tools/screenshots/workspace-${width}.png`, fullPage: true });
    await page.getByRole('tab', { name: 'Files', exact: true }).click();
    await page.getByRole('button', { name: /docs, 1 files; 50 B/ }).click();
    await page.getByRole('button', { name: /docs\/guide.md/ }).click();
    await page.locator('pre').filter({ hasText: 'Project instructions' }).waitFor();
    if (await page.locator('.file-row[aria-current="true"]').count() !== 1) throw new Error('Selected file is not identified');
    if (!(await page.locator('time[datetime="2026-09-11T10:20:00.000Z"]').count())) throw new Error('Modified dates are missing');
    if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)) throw new Error(`File metadata overflows at ${width}`);
